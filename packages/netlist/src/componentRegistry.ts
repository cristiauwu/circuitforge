export const COMPONENT_INDEX: ReadonlyMap<string, ComponentDefinition> = new Map(
  COMPONENT_DEFINITIONS.map((definition) => [definition.typeId, definition]),
)

/** A fresh record on every call; unknown component types have no defaults. */
export function getDefaultParameters(typeId: string): Record<string, ParamValue> {
  return Object.fromEntries(
    (COMPONENT_INDEX.get(typeId)?.parameters ?? []).map(({ key, defaultValue }) => [
      key,
      defaultValue,
    ]),
  )
}

/** Reject unknown types/keys, coercion, non-finite numbers and values off the declared grid. */
export function validateParameterValue(typeId: string, key: string, value: unknown): boolean {
  const parameter = COMPONENT_INDEX.get(typeId)?.parameters.find((item) => item.key === key)
  if (!parameter) return false
  if (parameter.kind === 'boolean') return typeof value === 'boolean'
  if (parameter.kind === 'enum') {
    return typeof value === 'string' && parameter.options.some((option) => option.value === value)
  }
  if (typeof value !== 'number' || !Number.isFinite(value)) return false
  if (parameter.min !== undefined && value < parameter.min) return false
  if (parameter.max !== undefined && value > parameter.max) return false
  if (parameter.step !== undefined) {
    const steps = (value - (parameter.min ?? 0)) / parameter.step
    if (Math.abs(steps - Math.round(steps)) > 1e-9) return false
  }
  return true
}
