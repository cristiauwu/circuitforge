import { BREADBOARD_CONTACTS } from './breadboard.js'
import type { Category, ParamValue, PinType } from './types.js'

export interface ComponentPinDefinition {
  id: string
  type: PinType
  required?: boolean
  powerRole?: 'input' | 'output' | 'reference'
}

interface ParameterBase {
  key: string
  label: string
}

export type ParameterDefinition =
  | (ParameterBase & {
      kind: 'number'
      unit?: string
      defaultValue: number
      min?: number
      max?: number
      step?: number
    })
  | (ParameterBase & { kind: 'boolean'; defaultValue: boolean })
  | (ParameterBase & {
      kind: 'enum'
      options: readonly { value: string; label: string }[]
      defaultValue: string
    })

/** Pure domain catalog; dimensions use project units, not renderer/world units. */
export interface ComponentDefinition {
  typeId: string
  name: string
  description: string
  category: Category
  referencePrefix: string
  pins: ComponentPinDefinition[]
  parameters: ParameterDefinition[]
  footprint: { width: number; depth: number }
  visualFamily: string
  electronic: boolean
}

const passive = (...ids: string[]): ComponentPinDefinition[] =>
  ids.map((id) => ({ id, type: 'passive' }))
const signal = (id: string, type: PinType = 'digital'): ComponentPinDefinition => ({
  id,
  type,
  required: false,
})
const supply = (id = 'VCC', output = false): ComponentPinDefinition => ({
  id,
  type: 'power',
  powerRole: output ? 'output' : 'input',
})
const ground = (id = 'GND'): ComponentPinDefinition => ({
  id,
  type: 'gnd',
  powerRole: 'reference',
})
const number = (
  key: string,
  label: string,
  defaultValue: number,
  unit?: string,
  min = 0,
  max?: number,
  step?: number,
): ParameterDefinition => ({
  key,
  label,
  kind: 'number',
  defaultValue,
  min,
  ...(unit !== undefined ? { unit } : {}),
  ...(max !== undefined ? { max } : {}),
  ...(step !== undefined ? { step } : {}),
})
const boolean = (key: string, label: string): ParameterDefinition => ({
  key,
  label,
  kind: 'boolean',
  defaultValue: false,
})
const choice = (
  key: string,
  label: string,
  values: readonly string[],
  defaultValue = values[0] ?? '',
): ParameterDefinition => ({
  key,
  label,
  kind: 'enum',
  options: values.map((value) => ({ value, label: value })),
  defaultValue,
})
function define(
  typeId: string,
  name: string,
  description: string,
  category: Category,
  referencePrefix: string,
  pins: ComponentPinDefinition[],
  width: number,
  depth: number,
  visualFamily: string,
  parameters: ParameterDefinition[] = [],
  electronic = true,
): ComponentDefinition {
  return {
    typeId,
    name,
    description,
    category,
    referencePrefix,
    pins,
    parameters,
    footprint: { width, depth },
    visualFamily,
    electronic,
  }
}

